// Structural review of the non-executed SQL draft. No DB connection or mutation.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const sql = fs.readFileSync(path.join(__dirname, '../database/drafts/20260907_billing_ownership_foundation.sql'), 'utf8')
const executableSql = sql.replace(/\/\*[\s\S]*?\*\//g, '').replace(/--.*$/gm, '')
for (const table of ['billing_operations', 'billing_recipient_plans', 'billing_units', 'billing_recipient_plan_overrides', 'billing_unit_events', 'ownership_transfers']) {
  assert.match(sql, new RegExp(`CREATE TABLE public\\.${table} \\(`))
  assert.match(sql, new RegExp(`ALTER TABLE public\\.${table} ENABLE ROW LEVEL SECURITY`))
}
assert.match(sql, /Draft migration blocked/)
assert.match(sql, /FOREIGN KEY \(contract_id, project_id\)/)
assert.match(sql, /FOREIGN KEY \(recipient_plan_id, project_id\)/)
assert.match(sql, /recipient_plan_id, project_id\)[\s\S]*MATCH SIMPLE/)
assert.match(sql, /billing_units_project_occurrence_uidx[\s\S]*\(project_id, occurrence_key\)/)
assert.match(sql, /REFERENCES public\.billing_operations\(operation_key, project_id\)/)
assert.match(sql, /frozen_amount IS NULL.*frozen_line_items IS NULL/)
assert.match(sql, /Frozen amount and line item total do not match/)
assert.match(sql, /from_customer_id <> to_customer_id/)
assert.match(sql, /append-only/)
assert.doesNotMatch(sql, /ON DELETE CASCADE/i)
assert.match(sql, /reason IS NOT NULL AND length\(trim\(reason\)\) > 0/)
assert.match(sql, /lifecycle <> 'fixed' OR original_method = 'direct_debit'/)
assert.match(sql, /BEFORE TRUNCATE ON public\.billing_unit_events/)
assert.match(sql, /BEFORE TRUNCATE ON public\.ownership_transfers/)
assert.match(sql, /current_setting\('ageful\.allow_draft_migration'/)
assert.doesNotMatch(executableSql, /GENERATED BY DEFAULT AS IDENTITY/i)
assert.doesNotMatch(executableSql, /CREATE POLICY/i)
assert.doesNotMatch(executableSql, /SECURITY DEFINER/i)
assert.doesNotMatch(executableSql, /INSERT INTO public\./i, 'Draft must not contain backfill data writes')
console.log('PASS: guarded schema draft separates plans, units and audit histories without public access, cascade deletion or backfill writes.')
